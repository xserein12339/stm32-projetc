/* ========================================================================== */
/*                          模块静态状态                                        */
/* ========================================================================== */

/** OLED 设备（init 阶段获取） */
static dal_display_dev_t *s_dev;

/** 硬件已初始化标志（首次 show 时惰性初始化） */
static bool s_hw_ready;

/** 行渲染缓冲：16B/行 × 8 行 = 128B（单任务调用契约，模块静态单份） */
static uint8_t s_line_buf[128];

/* ========================================================================== */
/*                          内部函数                                            */
/* ========================================================================== */

/**
 * @brief   置 1bpp 行 Major 缓冲中的单像素
 * @param[in] x 列（0~127）
 * @param[in] y 行（0~7，页内行）
 */
static inline void pixel_set(uint8_t x, uint8_t y)
{
    s_line_buf[(uint16_t)y * 16U + (x >> 3)] |= (uint8_t)(0x80U >> (x & 0x07U));
}

/**
 * @brief   渲染一行文本到页 page 并提交 draw
 *
 * @param[in] page 目标页（0~7，即屏幕第 page 行文本）
 * @param[in] text 文本（截断到 APP_HMI_LINE_CHARS 字符）
 */
static void line_render(uint8_t page, const char *text)
{
    memset(s_line_buf, 0, sizeof(s_line_buf));

    for (uint8_t i = 0; i < APP_HMI_LINE_CHARS && text[i] != '\0'; i++) {
        uint8_t ch = (uint8_t)text[i];
        if (ch < 32U || ch > 126U) {
            ch = '?';               /* 不可打印字符统一替换 */
        }

        const uint8_t *glyph = s_font5x7[ch - 32U];
        uint8_t x0 = (uint8_t)(i * 6U);

        for (uint8_t k = 0; k < 5U; k++) {      /* 5 列字形 */
            uint8_t col = glyph[k];
            for (uint8_t r = 0; r < 7U; r++) {
                if ((col & (uint8_t)(1U << r)) != 0U) {
                    pixel_set((uint8_t)(x0 + k), r);
                }
            }
        }
        /* 第 6 列留空隙：无需操作（缓冲已清零） */
    }

    dal_display_rect_t rect = {
        .x = 0, .y = (uint16_t)(page * 8U), .w = 128U, .h = 8U,
    };
    /* BUSY（DMA 进行中）直接忽略，下个刷新周期重画 */
    (void)dal_display_draw(s_dev, &rect, s_line_buf, sizeof(s_line_buf));
}

/* ========================================================================== */
/*                              公开 API                                        */
/* ========================================================================== */

int32_t app_hmi_init(void)
{
    s_dev = dal_display_get_dev("oled");
    return (s_dev != NULL) ? 0 : -1;
}

void app_hmi_show(const char *const *lines, uint8_t line_count)
{
    if (s_dev == NULL || lines == NULL) {
        return;
    }
    if (line_count > APP_HMI_LINE_COUNT) {
        line_count = APP_HMI_LINE_COUNT;
    }

    /* 惰性硬件初始化：调度器启动后首次调用时执行（I2C 阻塞写） */
    if (!s_hw_ready) {
        if (dal_display_init(s_dev) != DAL_OK) {
            return;
        }
        s_hw_ready = true;
    }

    for (uint8_t i = 0; i < line_count; i++) {
        if (lines[i] != NULL) {
            line_render(i, lines[i]);
        }
    }

    (void)dal_display_flush_async(s_dev);
}
